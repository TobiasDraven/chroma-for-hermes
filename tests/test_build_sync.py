"""The build-currency gate: the shipped build must match what the generator produces.

`chroma/desktop/plugin.js` is COMMITTED, because the installer loads it: the
Desktop plugin is a build artifact, not a source file. The source of truth is
`chroma/desktop/plugin.template.js` plus the `skins-v2/` catalogue, and
`scripts/regenerate.py` turns those into the shipped bytes.

That arrangement has one failure mode, and it is silent: edit the template (or
add a skin) and do not regenerate. Every gate in the repo still passes - the
tests exercise the stale build, the catalogue contract is intact, the package
contract is intact - and the plugin that installs is the one you wrote before
the edit. Nothing says "this file is older than the thing that produced it".

So this module regenerates the build and compares it to what is committed:

  1. the generator must run clean in a THROWAWAY COPY of the repo;
  2. the copy's `chroma/desktop/plugin.js` must be BYTE-IDENTICAL to the committed one;
  3. the copy's `gateway-skins/` must be the same FILE SET, byte for byte;
  4. the copy's `docs/DERIVED-PALETTES.md` must match the committed one;
  5. the template must still carry the `__SKINS_DATA__` placeholder the
     generator substitutes, and the template and the generated build must agree
     on the `BUILD_STAMP` literal.

The generator is NEVER run against the working tree: it rewrites committed
files in place, which would turn a failing gate into a passing one by editing
the evidence. Everything happens in a temp copy, and the comparison is always
copy-vs-repo.

The repo root is a parameter, not a constant: `CHROMA_BUILD_SYNC_REPO_ROOT`
points the gate at another tree. That is how the gate is fault-injected - a
COPY of the repo is mutated, the gate is pointed at the copy, and the gate has
to go RED. A gate that has never failed is not a gate.

The safe generator form is used throughout: `python scripts/regenerate.py`, with
no positional output directory. The positional form takes its skins directory
and output path from argv and does not write the gateway transports or the
derived-palette report, so it is not a build.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import NamedTuple

import pytest

# The repo this test file lives in. Overridden by CHROMA_BUILD_SYNC_REPO_ROOT.
REPO_ROOT = Path(__file__).resolve().parent.parent

# The gate can be pointed at another tree. It is read-only input: the gate
# still writes only inside its own throwaway copy, so pointing it at a mutated
# copy cannot damage anything.
REPO_ROOT_ENV = "CHROMA_BUILD_SYNC_REPO_ROOT"

# Copied out of the repo, never copied INTO it. These are either huge, private
# to this machine, or regenerated by other tools; none of them affect the build.
EXCLUDED_NAMES = (
    ".git",
    "node_modules",
    ".venv",
    "__pycache__",
    ".pytest_cache",
    "cache",
    "scratch",
    ".rigour",
    ".serena",
    "*.pyc",
)

TEMPLATE_REL = Path("chroma") / "desktop" / "plugin.template.js"
BUILD_REL = Path("chroma") / "desktop" / "plugin.js"
GATEWAY_REL = Path("gateway-skins")
DERIVED_REL = Path("docs") / "DERIVED-PALETTES.md"
GENERATOR_REL = Path("scripts") / "regenerate.py"

# The literal the generator substitutes with the serialised skin catalogue.
SKINS_PLACEHOLDER = "__SKINS_DATA__"

# The build stamp is the one hand-written value that survives into the build,
# so it is the one place where "the template and the build agree" is checkable
# without regenerating anything.
BUILD_STAMP_RE = re.compile(r"const\s+BUILD_STAMP\s*=\s*(['\"])(?P<stamp>[^'\"]*)\1")


class BuildCopy(NamedTuple):
    """A throwaway copy of the repo with the generator run inside it."""

    source: Path
    tree: Path
    result: subprocess.CompletedProcess


def repo_root() -> Path:
    """The tree under test: this repo, or the one named by the environment."""
    override = os.environ.get(REPO_ROOT_ENV)
    if override:
        return Path(override).resolve()
    return REPO_ROOT


def build_stamp(text: str) -> str | None:
    """Return the BUILD_STAMP literal declared in a source file, if any."""
    match = BUILD_STAMP_RE.search(text)
    return match.group("stamp") if match else None


def first_difference(expected: bytes, actual: bytes) -> str:
    """Describe where two byte strings part ways, for a failure message."""
    limit = min(len(expected), len(actual))
    for index in range(limit):
        if expected[index] != actual[index]:
            start = max(0, index - 60)
            end = index + 60
            return (
                f"first difference at byte {index} of {max(len(expected), len(actual))}\n"
                f"  committed: ...{expected[start:end]!r}...\n"
                f"  generated: ...{actual[start:end]!r}..."
            )
    return (
        f"the two files agree byte for byte up to {limit} bytes and then differ in "
        f"length: committed={len(expected)} generated={len(actual)}"
    )


@pytest.fixture(scope="module")
def build_copy(tmp_path_factory: pytest.TempPathFactory) -> BuildCopy:
    """Copy the repo to a temp dir and run the generator inside the copy.

    The copy is what gets regenerated; the repo is what gets compared against.
    Nothing under the repo is written to.
    """
    source = repo_root()
    generator = source / GENERATOR_REL
    assert generator.is_file(), (
        f"{source} does not look like the plugin repo: {GENERATOR_REL} is missing"
    )

    tree = tmp_path_factory.mktemp("build-sync") / "repo"
    shutil.copytree(
        source,
        tree,
        ignore=shutil.ignore_patterns(*EXCLUDED_NAMES),
    )

    # The SAFE form: no positional skins dir, no positional output path. The
    # positional form is a different code path that writes neither the gateway
    # transports nor the derived-palette report, so it is not a build.
    result = subprocess.run(
        [sys.executable, str(Path("scripts") / "regenerate.py")],
        cwd=str(tree),
        capture_output=True,
        text=True,
        timeout=600,
    )
    return BuildCopy(source=source, tree=tree, result=result)


def test_generator_runs_clean_in_the_throwaway_copy(build_copy: BuildCopy) -> None:
    """The generator must succeed before any of its output means anything."""
    result = build_copy.result
    assert result.returncode == 0, (
        f"scripts/regenerate.py failed in the throwaway copy "
        f"(exit {result.returncode})\n"
        f"--- stdout ---\n{result.stdout}\n"
        f"--- stderr ---\n{result.stderr}"
    )


def test_generated_build_is_byte_identical_to_the_committed_build(build_copy: BuildCopy) -> None:
    """The core assertion: what ships is what the template + catalogue generate."""
    committed = build_copy.source / BUILD_REL
    generated = build_copy.tree / BUILD_REL

    assert committed.is_file(), f"the repo has no committed {BUILD_REL}"
    assert generated.is_file(), (
        f"the generator did not write {BUILD_REL} in the copy; "
        f"stdout:\n{build_copy.result.stdout}\nstderr:\n{build_copy.result.stderr}"
    )

    committed_bytes = committed.read_bytes()
    generated_bytes = generated.read_bytes()
    assert committed_bytes == generated_bytes, (
        f"the committed {BUILD_REL} is NOT what the template and the catalogue "
        f"generate - the shipped build is stale. Re-run "
        f"`python scripts/regenerate.py` and commit the result.\n"
        f"{first_difference(committed_bytes, generated_bytes)}"
    )


def test_gateway_transports_match_the_committed_ones(build_copy: BuildCopy) -> None:
    """Same file set, same bytes: a transport is a shipped artifact too."""
    committed_dir = build_copy.source / GATEWAY_REL
    if not committed_dir.is_dir():
        pytest.skip(f"the repo has no {GATEWAY_REL}/ directory")

    generated_dir = build_copy.tree / GATEWAY_REL
    assert generated_dir.is_dir(), (
        f"the generator did not write {GATEWAY_REL}/ in the copy; "
        f"stdout:\n{build_copy.result.stdout}\nstderr:\n{build_copy.result.stderr}"
    )

    committed = {p.name: p.read_bytes() for p in committed_dir.iterdir() if p.is_file()}
    generated = {p.name: p.read_bytes() for p in generated_dir.iterdir() if p.is_file()}

    missing = sorted(set(committed) - set(generated))
    extra = sorted(set(generated) - set(committed))
    assert not missing, (
        f"the generator did not write these committed transports: {missing}. "
        f"Re-run `python scripts/regenerate.py` and commit the result."
    )
    assert not extra, (
        f"the generator wrote transports the repo does not have: {extra}. "
        f"Re-run `python scripts/regenerate.py` and commit the result."
    )

    for name in sorted(committed):
        assert committed[name] == generated[name], (
            f"{GATEWAY_REL}/{name} differs from the committed transport.\n"
            f"{first_difference(committed[name], generated[name])}"
        )


def test_derived_palettes_report_matches_the_committed_one(build_copy: BuildCopy) -> None:
    """The derivation report is generated too, so it is covered by the gate."""
    committed = build_copy.source / DERIVED_REL
    if not committed.is_file():
        pytest.skip(f"the repo has no {DERIVED_REL}")

    generated = build_copy.tree / DERIVED_REL
    assert generated.is_file(), (
        f"the generator did not write {DERIVED_REL} in the copy; "
        f"stdout:\n{build_copy.result.stdout}\nstderr:\n{build_copy.result.stderr}"
    )

    committed_bytes = committed.read_bytes()
    generated_bytes = generated.read_bytes()
    assert committed_bytes == generated_bytes, (
        f"the committed {DERIVED_REL} is NOT what the generator writes - "
        f"re-run `python scripts/regenerate.py` and commit the result.\n"
        f"{first_difference(committed_bytes, generated_bytes)}"
    )


def test_template_still_carries_the_skins_placeholder(build_copy: BuildCopy) -> None:
    """The template must keep the hook the generator substitutes into."""
    template = build_copy.source / TEMPLATE_REL
    assert template.is_file(), f"the repo has no {TEMPLATE_REL}"

    text = template.read_text(encoding="utf-8")
    assert SKINS_PLACEHOLDER in text, (
        f"{TEMPLATE_REL} no longer contains the {SKINS_PLACEHOLDER} placeholder. "
        f"The generator has nothing to substitute, so the shipped build would "
        f"stop carrying the catalogue."
    )


def test_generated_build_has_no_unsubstituted_placeholder(build_copy: BuildCopy) -> None:
    """A placeholder that survives the substitution is a build that cannot run."""
    generated = build_copy.tree / BUILD_REL
    assert generated.is_file(), f"the generator did not write {BUILD_REL} in the copy"

    text = generated.read_text(encoding="utf-8")
    assert SKINS_PLACEHOLDER not in text, (
        f"the generated {BUILD_REL} still contains {SKINS_PLACEHOLDER}: the "
        f"substitution did not happen, so the build is not valid JavaScript."
    )


def test_build_stamp_agrees_between_the_template_and_the_generated_build(build_copy: BuildCopy) -> None:
    """The template and the build must agree on the one literal both carry."""
    template_text = (build_copy.source / TEMPLATE_REL).read_text(encoding="utf-8")
    generated_text = (build_copy.tree / BUILD_REL).read_text(encoding="utf-8")

    template_stamp = build_stamp(template_text)
    generated_stamp = build_stamp(generated_text)

    assert template_stamp is not None, f"{TEMPLATE_REL} declares no BUILD_STAMP literal"
    assert generated_stamp is not None, f"{BUILD_REL} declares no BUILD_STAMP literal"
    assert template_stamp == generated_stamp, (
        f"the template's BUILD_STAMP is {template_stamp!r} but the generated "
        f"build says {generated_stamp!r}"
    )
