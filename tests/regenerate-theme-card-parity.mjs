// Regenerate tests/fixtures/theme-card-parity.json.
//
// Run this ONLY when a change to the card's rendered output is INTENDED, and say
// so in the commit message. It records the DOM that ThemeCard produces for every
// case in tests/helpers/card-cases.mjs, which is what lets a refactor of the card
// be proven not to change what the user sees.
//
//   node tests/regenerate-theme-card-parity.mjs
import { writeFile } from 'node:fs/promises'
import { loadPlugin } from './helpers/load-plugin.mjs'
import { CARD_CASES, BASE_CARD_PROPS, cardSpies, digestElement } from './helpers/card-cases.mjs'

const { context } = await loadPlugin()
const ThemeCard = context.testHelpers.ThemeCard

const cases = {}
for (const [label, overrides] of Object.entries(CARD_CASES)) {
  cases[label] = digestElement(ThemeCard({ ...cardSpies(), ...BASE_CARD_PROPS, ...overrides }))
}

const fixture = {
  note: 'Rendered DOM of ThemeCard per case. Generated by tests/regenerate-theme-card-parity.mjs. Do not hand-edit.',
  cases
}

const target = new URL('./fixtures/theme-card-parity.json', import.meta.url)
await writeFile(target, JSON.stringify(fixture, null, 1) + '\n')
console.log(`wrote ${Object.keys(cases).length} card cases`)
